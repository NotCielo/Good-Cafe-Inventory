import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const env=Object.fromEntries(fs.readFileSync('.env.local','utf8').trim().split(/\r?\n/).map(x=>x.split('=')));
test('PIN access, stock audit, purchases, permissions, and mobile layout',async({page,browser})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('/');
 await page.getByLabel('Four-digit passcode').fill('9999');
 await page.getByRole('button',{name:'Open workspace'}).click();
 await expect(page.getByRole('alert')).toContainText('isn’t correct');
 await page.getByLabel('Four-digit passcode').fill(env.TEST_ADMIN_PIN);
 await page.getByRole('button',{name:'Open workspace'}).click();
 await expect(page.getByRole('heading',{name:'Your inventory.'})).toBeVisible();
 await page.getByRole('button',{name:'Add item',exact:true}).click();
 await page.getByLabel('Item name *').fill('__Verification Espresso Beans');
 await page.getByLabel('Category *').selectOption('6');
 await page.getByLabel('Unit *').fill('kg');
 await page.getByLabel('Reorder level *').fill('2');
 await page.getByLabel('Where to buy',{exact:true}).fill('Test supplier');
 await page.getByRole('button',{name:'Save item',exact:true}).click();
 let row=page.getByRole('row').filter({hasText:'__Verification Espresso Beans'});
 await expect(row).toBeVisible();
 await row.getByRole('button',{name:'Update stock'}).click();
 await page.getByLabel('Quantity (kg) *').fill('5');
 await page.getByLabel('Your name *').fill('Verification');
 await page.getByRole('button',{name:'Save stock update'}).click();
 await expect(row.locator('.stock-number>strong')).toHaveText('5');
 await row.getByRole('button',{name:'Update stock'}).click();
 await page.getByText('Remove stock',{exact:true}).click();
 await page.getByLabel('Quantity (kg) *').fill('6');
 await page.getByLabel('Your name *').fill('Verification');
 await page.getByRole('button',{name:'Save stock update'}).click();
 await expect(page.locator('#modal-error')).toContainText('Cannot remove more');
 await page.getByLabel('Quantity (kg) *').fill('4');
 await page.getByRole('button',{name:'Save stock update'}).click();
 await expect(row.locator('.stock-number>strong')).toHaveText('1');
 await page.getByRole('link',{name:/Needs to buy/}).click();
 const card=page.locator('.buy-card').filter({hasText:'__Verification Espresso Beans'});
 await card.getByRole('button',{name:'Set quantity'}).click();
 await page.getByLabel('Quantity (kg)',{exact:true}).fill('3');
 await page.getByRole('button',{name:'Save quantity'}).click();
 await card.getByRole('button',{name:'Log purchase'}).click();
 await page.getByLabel('Your name *').fill('Verification');
 await page.getByRole('button',{name:'Record purchase'}).click();
 await expect(card.locator('.buy-card-qty strong')).toContainText('1');
 await page.screenshot({path:'test-results/desktop-buy-list.png',fullPage:true});
 await page.getByRole('link',{name:'Activity log'}).click();
 await expect(page.getByRole('cell',{name:'Verification',exact:true}).first()).toBeVisible();
 await page.getByRole('button',{name:'Purchases',exact:true}).click();
 await expect(page.getByRole('cell',{name:'__Verification Espresso Beans',exact:true})).toBeVisible();
 // Independent simultaneous stock requests must both be retained.
 const token=await page.evaluate(()=>{const k=Object.keys(sessionStorage).find(k=>k.endsWith('-auth-token'));return JSON.parse(sessionStorage.getItem(k)).access_token;});
 const call=async(action,payload={})=>{const r=await page.request.post(env.VITE_SUPABASE_URL+'/functions/v1/inventory',{headers:{apikey:env.VITE_SUPABASE_PUBLISHABLE_KEY,Authorization:'Bearer '+token},data:{action,payload}});expect(r.status()).toBe(200);return r.json();};
 const before=await call('load');const item=before.items.find(x=>x.name==='__Verification Espresso Beans');
 await Promise.all([call('stock',{id:item.id,amount:2,direction:'add',staff_name:'Concurrent Verification A'}),call('stock',{id:item.id,amount:3,direction:'add',staff_name:'Concurrent Verification B'})]);
 const after=await call('load');expect(Number(after.items.find(x=>x.id===item.id).quantity)).toBe(6);
 await call('stock',{id:item.id,amount:5,direction:'subtract',staff_name:'Verification reset'});
 await page.getByRole('button',{name:/Admin workspace/}).click();
 await page.getByLabel('Four-digit passcode').fill(env.TEST_STAFF_PIN);
 await page.getByRole('button',{name:'Open workspace'}).click();
 await expect(page.getByRole('heading',{name:'Your inventory.'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Add item',exact:true})).toHaveCount(0);
 await expect(page.getByRole('link',{name:'Categories',exact:true})).toHaveCount(0);
 row=page.getByRole('row').filter({hasText:'__Verification Espresso Beans'});
 await row.getByRole('button',{name:'Update stock'}).click();
 await page.getByLabel('Quantity (kg) *').fill('0.5');
 await page.getByLabel('Your name *').fill('Staff Verification');
 await page.getByRole('button',{name:'Save stock update'}).click();
 await expect(row.locator('.stock-number>strong')).toHaveText('1.5');
 await page.screenshot({path:'test-results/desktop-inventory.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await expect(page.getByRole('heading',{name:'Your inventory.'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Open navigation'}).click();
 await page.getByRole('link',{name:/Needs to buy/}).click();
 await expect(page.locator('.buy-card h3')).toContainText('__Verification Espresso Beans');
 await page.screenshot({path:'test-results/mobile-buy-list.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(errors).toEqual([]);
});
